  static final _namePattern = RegExp(
    r"^\p{L}[\p{L}\p{M}]*(?:[ '\u2019-]\p{L}[\p{L}\p{M}]*)*$",
    unicode: true,
  );

  static String normalize(String value) =>
      value.trim().replaceAll(RegExp(r' +'), ' ');

  /// Returns a user-facing error, or null when the name is accepted.
  static String? validate(String value) {
    // Reject control characters before trimming, including pasted newlines.
    if (RegExp(r'[\x00-\x1F\x7F]').hasMatch(value)) {
      return 'Use apenas letras, espaços, hífen e apóstrofo no nome.';
    }

    final name = normalize(value);
    if (name.isEmpty) return 'Informe o nome.';
    if (name.runes.length > maxLength) {
      return 'O nome deve ter no máximo $maxLength caracteres.';
    }
    if (!_namePattern.hasMatch(name)) {
      return 'Use letras e separe os nomes com espaço, hífen ou apóstrofo.';
    }

    final words = _foldAccents(name).split(RegExp(r"[ '\u2019-]+"));
    if (words.any(_blockedWords.contains)) {
      return 'O nome contém um termo não permitido. Informe outro nome.';
    }
    return null;
  }

  static String _foldAccents(String value) {
    var result = value.toLowerCase();
    const groups = {
      'a': 'áàâãäå',
      'e': 'éèêë',
      'i': 'íìîï',
      'o': 'óòôõö',
      'u': 'úùûü',
      'c': 'ç',
    };
    for (final entry in groups.entries) {
      for (final rune in entry.value.runes) {
        result = result.replaceAll(String.fromCharCode(rune), entry.key);
      }
    }
    return result.replaceAll(RegExp(r'\p{M}', unicode: true), '');
  }
